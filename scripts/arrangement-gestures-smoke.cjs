// Real Chromium input against the production renderer, used by electron-smoke.
module.exports = async function arrangementGestures(window, evaluate, waitFor, delay) {
  const run = (source, label) => evaluate(window, source, label)
  const wait = (source, label) => waitFor(window, source, label)
  async function key(keyCode, modifiers = []) {
    window.webContents.sendInputEvent({ type: 'keyDown', keyCode, modifiers })
    window.webContents.sendInputEvent({ type: 'keyUp', keyCode, modifiers })
    await delay(60)
  }
  async function rect(selector) {
    return run(`(() => {const r=document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect();return {x:Math.round((Math.max(0,r.left)+Math.min(innerWidth,r.right))/2),y:Math.round((Math.max(0,r.top)+Math.min(innerHeight,r.bottom))/2)}})()`, `locate ${selector}`)
  }
  async function drag(selector, dx, cancel = false) {
    const { x, y } = await rect(selector)
    window.focus()
    window.webContents.sendInputEvent({ type: 'mouseMove', x, y })
    await delay(40)
    window.webContents.sendInputEvent({ type: 'mouseDown', x, y, button: 'left', clickCount: 1 })
    await delay(40)
    window.webContents.sendInputEvent({ type: 'mouseMove', x: Math.round(x + dx), y, modifiers: ['leftButtonDown'] })
    await delay(60)
    if (cancel) await key('Escape')
    window.webContents.sendInputEvent({ type: 'mouseUp', x: Math.round(x + dx), y, button: 'left', clickCount: 1 })
    await delay(60)
  }
  const count = await run(`document.querySelectorAll('.arrangement-block').length`, 'baseline arrangement count')
  await run(`document.activeElement.blur(); document.querySelector('.arrangement-block').click(); true`, 'focus arrangement')
  await key('a', ['control'])
  await wait(`document.querySelectorAll('.arrangement-block.selected').length === ${count}`, 'Ctrl+A selects arrangement')
  // A focused field keeps native text selection/deletion instead of editing clips.
  await run(`document.querySelector('input[aria-label="Track name"]').focus(); true`, 'focus editable name')
  await key('a', ['control'])
  const textSelection = await run(`(() => {const e=document.activeElement;return e.selectionStart===0 && e.selectionEnd===e.value.length})()`, 'native text selection')
  if (!textSelection) throw Error('Ctrl+A did not retain native field selection')
  await wait(`document.querySelectorAll('.arrangement-block').length === ${count}`, 'text editing preserves clips')
  await run(`document.activeElement.blur(); true`, 'restore arrangement keyboard focus')
  await key('Delete')
  await wait(`document.querySelectorAll('.arrangement-block').length === 0`, 'Delete removes selected group')
  await key('z', ['control'])
  await wait(`document.querySelectorAll('.arrangement-block').length === ${count}`, 'one undo restores group')
  await key('a', ['control']); await key('d', ['control'])
  await wait(`document.querySelectorAll('.arrangement-block').length === ${count * 2}`, 'Ctrl+D duplicates selected group')
  await key('Delete')
  await wait(`document.querySelectorAll('.arrangement-block').length === ${count}`, 'Delete removes duplicated group')
  await key('z', ['control']); await key('z', ['control'])
  await wait(`document.querySelectorAll('.arrangement-block').length === ${count}`, 'undo duplicate and delete independently')
  await run(`document.querySelector('.arrangement-block').click(); true`, 'select resize subject')
  const original = await run(`document.querySelector('.arrangement-block small').textContent`, 'original length')
  await drag('.arrangement-block .block-resize.right', 42.5)
  await wait(`document.querySelector('.arrangement-block small').textContent === ${JSON.stringify((parseFloat(original) + 1.25) + ' beats')}`, 'dragged edge snaps to quarter beat')
  await key('z', ['control'])
  await wait(`document.querySelector('.arrangement-block small').textContent === ${JSON.stringify(original)}`, 'one undo restores drag')
  await drag('.arrangement-block .block-resize.left', 34)
  await wait(`document.querySelector('.arrangement-block').style.left === '34px' && document.querySelector('.arrangement-block small').textContent === ${JSON.stringify((parseFloat(original) - 1) + ' beats')}`, 'left edge trims start and preserves end')
  await key('z', ['control'])
  await drag('.arrangement-block .block-resize.right', 68, true)
  await wait(`document.querySelector('.arrangement-block small').textContent === ${JSON.stringify(original)}`, 'Escape cancels resize preview')
  await key('a', ['control'])
  const lefts = await run(`[...document.querySelectorAll('.arrangement-block')].map(b=>parseFloat(b.style.left))`, 'original group positions')
  await drag('.arrangement-block .block-title', 34)
  await wait(`[...document.querySelectorAll('.arrangement-block')].every((b,i)=>parseFloat(b.style.left) === ${JSON.stringify(lefts)}[i]+34)`, 'group moves together')
  await key('z', ['control'])
  const anchor = await run(`(() => {const v=document.querySelector('.timeline-scroll'), r=v.getBoundingClientRect(), x=r.left+v.clientWidth/2, y=r.top+20;const pixels=parseFloat(document.querySelector('.ruler span').style.width)/4;return {x:Math.round(x),y:Math.round(y),beat:(v.scrollLeft+Math.round(x)-r.left-112)/pixels,zoom:document.querySelector('.arrange-tools b').textContent}})()`, 'wheel zoom anchor')
  window.webContents.sendInputEvent({ type: 'mouseWheel', x: anchor.x, y: anchor.y, deltaY: 100, deltaX: 0 })
  await wait(`document.querySelector('.arrange-tools b').textContent !== ${JSON.stringify(anchor.zoom)}`, 'mouse wheel changes zoom')
  const anchored = await run(`(() => {const v=document.querySelector('.timeline-scroll'),r=v.getBoundingClientRect(),pixels=parseFloat(document.querySelector('.ruler span').style.width)/4;return (v.scrollLeft+${anchor.x}-r.left-112)/pixels})()`, 'verify zoom anchor')
  if (Math.abs(anchored - anchor.beat) > .1) throw Error(`Wheel zoom lost cursor anchor: ${anchor.beat} -> ${anchored}`)
  await run(`document.querySelector('.timeline-scroll').scrollLeft=0; true`, 'reset timeline viewport')
  await drag('.ruler span:nth-child(2)', 13)
  const position = await run(`Number(document.querySelector('[aria-label="Song playhead"]').getAttribute('aria-valuenow'))`, 'scrubbed position')
  if (!(position > 0 && Math.abs(position * 4 - Math.round(position * 4)) > .001)) throw Error('Ruler seek should support unsnapped precise positions')
  await drag('.arrangement-playhead', 21)
  const moved = await run(`Number(document.querySelector('[aria-label="Song playhead"]').getAttribute('aria-valuenow'))`, 'dragged playhead position')
  if (!(moved > position)) throw Error('Dragging the red playhead did not seek forward')
  await drag('.timeline-seek-space', -19)
  await wait(`document.querySelector('.elapsed-time').textContent !== '00:00.000'`, 'elapsed readout follows seek')
  await run(`document.querySelector('button[aria-label="Return to start"]').click(); true`, 'reset playhead after gesture tests')
  await wait(`document.querySelector('.elapsed-time').textContent === '00:00.000'`, 'return to start resets elapsed time')
}
